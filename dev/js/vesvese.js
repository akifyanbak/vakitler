export function pickVesvese(random = Math.random) {
  const line = VESVESE_LINES[Math.floor(random() * VESVESE_LINES.length)];
  const face = 1 + Math.floor(random() * VESVESE_FACE_COUNT);
  return { title: VESVESE_TITLE, body: line, face };
}
